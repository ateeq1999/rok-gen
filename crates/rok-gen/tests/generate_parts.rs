//! `make:entity`, `make:repository`, `make:service`, `make:error` and
//! `routes`.

// Test harness code: panicking on a broken fixture is the point.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

mod common;

use common::Fixture;
use serde_json::Value;

fn ok(fixture: &Fixture, args: &[&str]) -> Value {
    let (code, outcome) = fixture.run_json(args);
    assert_eq!(code, 0, "{args:?}: {outcome:#}");
    outcome
}

fn refused(fixture: &Fixture, args: &[&str], expected: &str) {
    let execution = fixture.run(args);
    assert_eq!(execution.code, 2, "{args:?}: {}", execution.stdout);
    assert!(
        execution.stderr.contains(expected),
        "{args:?}: {}",
        execution.stderr
    );
}

#[test]
fn make_entity_adds_and_exports_the_entity() {
    let fixture = Fixture::app();
    ok(
        &fixture,
        &[
            "make:entity",
            "posts",
            "tag_label",
            "--field",
            "label:string",
            "--field",
            "weight:int?",
        ],
    );

    let entity = fixture.read("crates/posts/src/tag_label_entity.rs");
    assert!(entity.contains("pub struct TagLabel {"), "{entity}");
    assert!(entity.contains("pub struct NewTagLabel {"), "{entity}");
    assert!(entity.contains("pub weight: Option<i32>,"), "{entity}");
    let lib = fixture.read("crates/posts/src/lib.rs");
    assert!(lib.contains("mod tag_label_entity;"), "{lib}");
    assert!(
        lib.contains("pub use tag_label_entity::{NewTagLabel, TagLabel, TagLabelUpdate};"),
        "{lib}"
    );
    let manifest = fixture.read("crates/posts/Cargo.toml");
    for dep in [
        "chrono.workspace = true",
        "uuid.workspace = true",
        "utoipa.workspace = true",
    ] {
        assert!(manifest.contains(dep), "{dep} missing:\n{manifest}");
    }
    assert_eq!(fixture.arch_rules(), Vec::<String>::new());

    refused(
        &fixture,
        &["make:entity", "posts", "tag_label", "--field", "a:string"],
        "already exists",
    );
}

#[test]
fn make_repository_adds_port_adapter_fake_and_table() {
    let fixture = Fixture::app();
    let outcome = ok(
        &fixture,
        &[
            "make:repository",
            "posts",
            "revision",
            "--field",
            "body:text",
            "--table",
            "post_revisions",
        ],
    );
    let created: Vec<&str> = outcome["files_created"]
        .as_array()
        .unwrap()
        .iter()
        .map(|file| file.as_str().unwrap())
        .collect();
    assert_eq!(
        created,
        [
            "crates/db/migrations/0002_create_post_revisions.sql",
            "crates/posts/src/revision_entity.rs",
            "crates/posts/src/revision_repository.rs",
        ]
    );

    let repository = fixture.read("crates/posts/src/revision_repository.rs");
    for expected in [
        "pub trait RevisionRepository: Send + Sync {",
        "pub struct PgRevisionRepository {",
        "FROM post_revisions WHERE id = $1",
        "pub mod fake {",
        "pub struct FakeRevisionRepository {",
        "async fn fake_round_trips() {",
        "-> Result<Option<Revision>, PostsError>",
    ] {
        assert!(
            repository.contains(expected),
            "{expected} missing:\n{repository}"
        );
    }
    assert!(
        fixture
            .read("crates/posts/src/lib.rs")
            .contains("pub use revision_repository::{PgRevisionRepository, RevisionRepository};")
    );
    let migration = fixture.read("crates/db/migrations/0002_create_post_revisions.sql");
    assert!(
        migration.starts_with(
            "-- Generated by `cargo rok make:repository`.\nCREATE TABLE post_revisions ("
        ),
        "{migration}"
    );
    assert!(
        fixture
            .read("crates/posts/Cargo.toml")
            .contains("sqlx.workspace = true")
    );
    assert_eq!(fixture.arch_rules(), Vec::<String>::new());
}

