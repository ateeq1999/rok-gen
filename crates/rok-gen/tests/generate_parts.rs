#[test]
fn make_service_depends_on_ports_and_is_wired_in() {
    let fixture = Fixture::app();
    ok(
        &fixture,
        &[
            "make:repository",
            "posts",
            "revision",
            "--field",
            "body:text",
        ],
    );
    ok(
        &fixture,
        &[
            "make:service",
            "posts",
            "publishing",
            "--repository",
            "post",
            "--repository",
            "revision",
        ],
    );

    let service = fixture.read("crates/posts/src/publishing_service.rs");
    assert!(
        service.contains("posts: Arc<dyn PostRepository>,"),
        "{service}"
    );
    assert!(
        service.contains("revisions: Arc<dyn RevisionRepository>,"),
        "{service}"
    );
    assert!(
        fixture
            .read("crates/posts/src/lib.rs")
            .contains("pub use publishing_service::PublishingService;")
    );

    let root = fixture.read("src/lib.rs");
    assert!(
        root.contains(
            "    let publishing_service = PublishingService::new(\n        Arc::new(PgPostRepository::new(pool.clone())),\n        Arc::new(PgRevisionRepository::new(pool.clone())),\n    );"
        ),
        "{root}"
    );
    assert!(
        root.contains(".app_data(web::Data::new(publishing_service.clone()))"),
        "{root}"
    );
    assert!(
        root.contains("use posts::{PgRevisionRepository, PublishingService};"),
        "{root}"
    );
    assert_eq!(fixture.arch_rules(), Vec::<String>::new());

    refused(
        &fixture,
        &["make:service", "posts", "publishing"],
        "already exists",
    );
    refused(
        &fixture,
        &["make:service", "posts", "other", "--repository", "nope"],
        "cargo rok make:repository posts nope",
    );
}

#[test]
fn routes_lists_every_registered_handler() {
    let fixture = Fixture::app();
    let outcome = ok(&fixture, &["routes"]);
    let routes: Vec<(String, String, String, bool)> = outcome["data"]["routes"]
        .as_array()
        .unwrap()
        .iter()
        .map(|route| {
            (
                route["method"].as_str().unwrap().to_string(),
                route["path"].as_str().unwrap().to_string(),
                route["handler"].as_str().unwrap().to_string(),
                route["guarded"].as_bool().unwrap(),
            )
        })
        .collect();
    assert_eq!(
        routes,
        [
            (
                "GET".to_string(),
                "/posts".to_string(),
                "posts::list_posts".to_string(),
                false
            ),
            (
                "POST".to_string(),
                "/posts".to_string(),
                "posts::create_post".to_string(),
                false
            ),
        ]
    );

    let table = fixture.run(&["routes"]).stdout;
    assert!(
        table.contains("GET     /posts  posts::list_posts"),
        "{table}"
    );
    assert!(table.ends_with("2 routes\n"), "{table}");
}

#[test]
fn routes_follow_module_guards() {
    let fixture = Fixture::app();
    fixture.replace(
        "crates/posts/src/post_module.rs",
        "controllers = [list_posts, create_post])]",
        "controllers = [list_posts], protected = [create_post], middleware = require_auth)]",
    );
    let outcome = ok(&fixture, &["routes"]);
    let guarded: Vec<bool> = outcome["data"]["routes"]
        .as_array()
        .unwrap()
        .iter()
        .map(|route| route["guarded"].as_bool().unwrap())
        .collect();
    assert_eq!(guarded, [false, true]);

    ok(
        &fixture,
        &["make:feature", "articles", "--field", "title:string"],
    );
    let table = fixture.run(&["routes"]).stdout;
    assert!(
        table.contains("DELETE  /articles/{id}  articles::delete_article  auth"),
        "{table}"
    );
    assert!(table.ends_with("7 routes\n"), "{table}");
}
